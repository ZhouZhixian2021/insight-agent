/**
 * Behaviour of the pre-merge conflict predictor against small throwaway repositories.
 *
 * Each case builds a repository with a tagged baseline and an `upstream/master`
 * branch that moved after it, then runs the shipped script with that repository
 * as its root. Copying the script into the fixture keeps its manifest lookup
 * (`<script>/upstream-overrides.json`) inside the fixture.
 */

import { execFileSync, spawnSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { afterEach, describe, expect, it } from 'vitest'

const HERE = dirname(fileURLToPath(import.meta.url))
const SCRIPT = join(HERE, 'impact.mjs')
const BASELINE_TAG = 'dsh-v0.2.1-rc.2'

const scratch: string[] = []

afterEach(() => {
  for (const directory of scratch.splice(0)) rmSync(directory, { recursive: true, force: true })
})

interface Fixture {
  repo: string
  git: (args: string[]) => void
  write: (path: string, content: string) => void
}

/** A repository whose baseline tag marks the release and whose `upstream/master` moved past it. */
function fixture(entries: unknown[]): Fixture {
  const repo = mkdtempSync(join(tmpdir(), 'dsh-impact-spec-'))
  scratch.push(repo)
  const git = (args: string[]): void => { execFileSync('git', args, { cwd: repo, stdio: 'ignore' }) }
  const write = (path: string, content: string): void => {
    mkdirSync(dirname(join(repo, path)), { recursive: true })
    writeFileSync(join(repo, path), content)
  }
  git(['init', '--quiet', '-b', 'main'])
  git(['config', 'user.email', 'spec@example.com'])
  git(['config', 'user.name', 'spec'])
  for (const [path, content] of Object.entries({
    'packages/core/src/a.ts': 'a\n',
    'packages/core/src/b.ts': 'b\n',
    'docs/catalog.md': 'Generated by gen-catalog.\n',
    'packages/core/src/d.ts': 'd\n',
  })) write(path, content)
  git(['add', '-A'])
  git(['commit', '--quiet', '-m', 'baseline'])
  git(['tag', BASELINE_TAG])
  git(['switch', '--quiet', '-c', 'upstream/master'])
  write('packages/core/src/a.ts', 'a upstream\n')
  write('packages/core/src/z.ts', 'unregistered\n')
  git(['add', '-A'])
  git(['rm', '--quiet', 'docs/catalog.md'])
  git(['commit', '--quiet', '-m', 'upstream moved'])
  write('scripts/upgrade/impact.mjs', readFileSync(SCRIPT, 'utf8'))
  write('scripts/upgrade/upstream-overrides.json', JSON.stringify({ upstream: { baseline: BASELINE_TAG }, entries }, null, 2))
  return { repo, git, write }
}

interface ImpactResult {
  status: number | null
  stdout: string
  stderr: string
}

function impact(repo: string, args: string[] = []): ImpactResult {
  const result = spawnSync(process.execPath, [join(repo, 'scripts/upgrade/impact.mjs'), ...args], {
    cwd: repo, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'],
  })
  return { status: result.status, stdout: result.stdout, stderr: result.stderr }
}

/** One registered rewrite that upstream changed heavily, one it deleted, two it left alone. */
function manifestEntries(): unknown[] {
  return [
    { path: 'packages/core/src/a.ts', category: 'fork', owner: 'spec', reason: 'x', addedLines: 2, removedLines: 1, upstreamChurn6mo: 10 },
    { path: 'packages/core/src/b.ts', category: 'fork', owner: 'spec', reason: 'x', addedLines: 1, removedLines: 0, upstreamChurn6mo: 1 },
    { path: 'docs/catalog.md', category: 'generated', owner: 'spec', reason: 'x', addedLines: 0, removedLines: 0, upstreamChurn6mo: 5 },
    { path: 'packages/core/src/d.ts', category: 'fork', owner: 'spec', reason: 'x', addedLines: 1, removedLines: 1, upstreamChurn6mo: 2 },
  ]
}

describe('impact', () => {
  it('lists the registered rewrites that upstream touched, riskiest first', () => {
    const { repo } = fixture(manifestEntries())
    const result = impact(repo)
    expect(result.status).toBe(0)
    expect(result.stdout).toContain('2 registered rewrite(s) will conflict')
    const lines = result.stdout.split('\n').filter(line => line.includes('packages/core/src/a.ts') || line.includes('docs/catalog.md'))
    expect(lines[0]).toContain('packages/core/src/a.ts')
    expect(lines[1]).toContain('docs/catalog.md')
  })

  it('marks a registered rewrite that upstream deleted', () => {
    const { repo } = fixture(manifestEntries())
    expect(impact(repo).stdout).toContain('(upstream deleted it)')
  })

  it('ignores upstream changes to files the manifest does not carry', () => {
    const { repo } = fixture(manifestEntries())
    const result = impact(repo, ['--json'])
    const report = JSON.parse(result.stdout) as { changed: number; hits: { path: string }[] }
    expect(report.changed).toBe(3)
    expect(report.hits.map(hit => hit.path)).not.toContain('packages/core/src/z.ts')
    expect(report.hits.map(hit => hit.path).sort()).toEqual(['docs/catalog.md', 'packages/core/src/a.ts'])
  })

  it('reports the deletion flag and the hashes in JSON', () => {
    const { repo } = fixture(manifestEntries())
    const report = JSON.parse(impact(repo, ['--json']).stdout) as {
      from: string
      to: string
      hits: { path: string; upstreamDeleted: boolean; risk: number }[]
    }
    expect(report.from).toHaveLength(12)
    expect(report.to).toHaveLength(12)
    const catalog = report.hits.find(hit => hit.path === 'docs/catalog.md')
    expect(catalog?.upstreamDeleted).toBe(true)
    expect(report.hits.find(hit => hit.path === 'packages/core/src/a.ts')?.upstreamDeleted).toBe(false)
  })

  it('exits 1 on an overlap only when --fail-on-overlap is passed', () => {
    const { repo } = fixture(manifestEntries())
    expect(impact(repo).status).toBe(0)
    expect(impact(repo, ['--fail-on-overlap']).status).toBe(1)
  })

  it('reports no conflict surface when the two refs are the same commit', () => {
    const { repo } = fixture(manifestEntries())
    const result = impact(repo, ['--to', BASELINE_TAG])
    expect(result.status).toBe(0)
    expect(result.stdout).toContain('no registered rewrite is touched')
  })

  it('exits 0 under --fail-on-overlap when nothing overlaps', () => {
    const { repo } = fixture(manifestEntries())
    expect(impact(repo, ['--to', BASELINE_TAG, '--fail-on-overlap']).status).toBe(0)
  })

  it('fails with exit code 2 when the baseline ref does not resolve', () => {
    const { repo } = fixture(manifestEntries())
    const result = impact(repo, ['--from', 'no-such-tag'])
    expect(result.status).toBe(2)
    expect(result.stderr).toContain('cannot resolve --from')
  })

  it('fails with exit code 2 when the manifest carries no baseline and none is passed', () => {
    const { repo } = fixture(manifestEntries())
    writeFileSync(join(repo, 'scripts/upgrade/upstream-overrides.json'), JSON.stringify({ entries: manifestEntries() }, null, 2))
    const result = impact(repo)
    expect(result.status).toBe(2)
    expect(result.stderr).toContain('no --from and no upstream.baseline')
  })

  it('uses --from over the recorded baseline', () => {
    const { repo, git } = fixture(manifestEntries())
    git(['switch', '--quiet', 'main'])
    expect(impact(repo, ['--from', 'main']).stdout).toContain('2 registered rewrite(s) will conflict')
  })
})
