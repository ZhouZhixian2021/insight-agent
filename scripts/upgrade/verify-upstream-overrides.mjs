#!/usr/bin/env node
/**
 * Enforce the upstream-override budget.
 *
 * Every upstream file this repository intentionally rewrites must be registered
 * in `upstream-overrides.json` with an owner, a reason and a category. The gate
 * fails when the tree and the manifest disagree, when a registration is
 * incomplete, when a file is filed under the wrong category, or when the fork
 * count grows past the recorded budget.
 *
 * Usage:
 *   node scripts/upgrade/verify-upstream-overrides.mjs                     # gate
 *   node scripts/upgrade/verify-upstream-overrides.mjs --against <ref>     # also flag new fork paths
 *   node scripts/upgrade/verify-upstream-overrides.mjs --allow-stale       # during an upgrade merge
 *   node scripts/upgrade/verify-upstream-overrides.mjs --list-generated    # paths to regenerate
 *   node scripts/upgrade/verify-upstream-overrides.mjs --restore-generated # git checkout --theirs them
 *   node scripts/upgrade/verify-upstream-overrides.mjs --report            # what is still incomplete
 *   node scripts/upgrade/verify-upstream-overrides.mjs --json
 *
 * Exit codes: 0 = in budget, 1 = gate failure, 2 = usage or environment error.
 */

import { spawnSync } from 'node:child_process'
import { closeSync, existsSync, mkdtempSync, openSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const MANIFEST_PATH = join(HERE, 'upstream-overrides.json')

/** Headers that mark a file as a build product; both locales are used upstream. */
const GENERATED_MARKER = /Generated by|generated by|do not edit|DO NOT EDIT|生成|请勿手工|禁止手工编辑|自动生成/u
/** Sidecars produced by `verify-translation-pairing --write`, not by hand. */
const GENERATED_SUFFIX = '.i18n.yaml'

/** @param {string[]} argv */
function parseArgs(argv) {
  const options = {
    base: 'upstream/master',
    against: undefined,
    repo: undefined,
    json: false,
    allowStale: false,
    report: false,
    listGenerated: false,
    restoreGenerated: false,
  }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--base') { options.base = argv[++index] ?? options.base; continue }
    if (arg === '--against') { options.against = argv[++index]; continue }
    if (arg === '--repo') { options.repo = argv[++index]; continue }
    if (arg === '--json') { options.json = true; continue }
    if (arg === '--allow-stale') { options.allowStale = true; continue }
    if (arg === '--report') { options.report = true; continue }
    if (arg === '--list-generated') { options.listGenerated = true; continue }
    if (arg === '--restore-generated') { options.restoreGenerated = true; continue }
    if (arg === '--help' || arg === '-h') { options.help = true; continue }
    throw new Error(`unknown argument: ${arg}`)
  }
  return options
}

/**
 * Run git and return stdout.
 *
 * Output lands in a scratch file instead of an anonymous pipe: a confined child
 * cannot open a named-pipe client end, so piped capture fails with EPERM where
 * file capture does not. The gate must run in the same shell agents use.
 *
 * @param {string} repo @param {string[]} args
 */
function git(repo, args) {
  const scratch = mkdtempSync(join(tmpdir(), 'dsh-upgrade-'))
  const out = join(scratch, 'out.txt')
  const fd = openSync(out, 'w')
  try {
    spawnSync('git', args, { cwd: repo, stdio: ['ignore', fd, fd] })
  } finally {
    closeSync(fd)
  }
  try {
    return readFileSync(out, 'utf8')
  } finally {
    rmSync(scratch, { recursive: true, force: true })
  }
}

/**
 * Whether `ref:path` exists in the object database.
 *
 * @param {string} repo @param {string} ref @param {string} path
 */
function fileExistsAt(repo, ref, path) {
  return spawnSync('git', ['cat-file', '-e', `${ref}:${path}`], { cwd: repo, stdio: 'ignore' }).status === 0
}

/**
 * Paths that differ from the merge base of `base` and `HEAD`.
 *
 * @param {string} repo @param {string} base
 */
function changedPaths(repo, base) {
  const mergeBase = git(repo, ['merge-base', base, 'HEAD']).trim()
  if (!mergeBase) {
    throw new Error(`no merge base with ${base}; fetch its full history (--filter=blob:none), not a --depth=1 clone`)
  }
  const raw = git(repo, ['diff', '--name-status', '-M', mergeBase, 'HEAD'])
  const modified = new Set()
  const added = new Set()
  for (const line of raw.split('\n')) {
    if (!line) continue
    const fields = line.split('\t')
    const status = fields[0]
    if (status.startsWith('R')) { modified.add(fields[1]); added.add(fields[2]) }
    else if (status.startsWith('M')) modified.add(fields[1])
    else if (status.startsWith('A')) added.add(fields[1])
  }
  return { mergeBase, modified, added }
}

/** @param {string} repo @param {string} path */
function readHead(repo, path) {
  const absolute = resolve(repo, path)
  if (!existsSync(absolute)) return ''
  return readFileSync(absolute, 'utf8').split('\n').slice(0, 3).join('\n')
}

/** @param {string} repo @param {string} path @param {string[]} exemptions */
function looksGenerated(repo, path, exemptions) {
  if (path.endsWith(GENERATED_SUFFIX)) return true
  if (exemptions.includes(path)) return true
  return GENERATED_MARKER.test(readHead(repo, path))
}

/** @param {unknown} value @param {string} what */
function requireString(value, what) {
  if (typeof value !== 'string' || value.trim() === '') throw new Error(`manifest: ${what} must be a non-empty string`)
  return value
}

function main() {
  const options = parseArgs(process.argv.slice(2))
  if (options.help) {
    process.stdout.write('verify-upstream-overrides [--base <ref>] [--against <ref>] [--repo <dir>] [--allow-stale] [--report] [--list-generated] [--restore-generated] [--json]\n')
    return 0
  }
  const repo = resolve(options.repo ?? join(HERE, '..', '..'))
  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'))
  requireString(manifest.budget?.maxForkFiles?.toString(), 'budget.maxForkFiles')
  const exemptions = manifest.generatedExemptions ?? []
  const registered = new Map()
  for (const entry of manifest.entries) {
    requireString(entry.path, 'entries[].path')
    requireString(entry.category, `category of ${entry.path}`)
    if (!['generated', 'wiring', 'fork'].includes(entry.category)) {
      throw new Error(`manifest: ${entry.path} has unknown category ${entry.category}`)
    }
    registered.set(entry.path, entry)
  }

  if (options.listGenerated) {
    for (const entry of manifest.entries) if (entry.category === 'generated') process.stdout.write(`${entry.path}\n`)
    return 0
  }
  if (options.restoreGenerated) {
    const paths = manifest.entries.filter(entry => entry.category === 'generated').map(entry => entry.path)
    if (paths.length === 0) return 0
    const result = spawnSync('git', ['checkout', '--theirs', '--', ...paths], { cwd: repo, stdio: 'inherit' })
    return result.status ?? 2
  }

  const { mergeBase, modified, added } = changedPaths(repo, options.base)
  const violations = []
  const stale = []
  const incomplete = []

  for (const path of modified) {
    if (!registered.has(path)) violations.push({ kind: 'unregistered-modification', path })
  }
  for (const [path, entry] of registered) {
    if (!modified.has(path)) stale.push({ path, category: entry.category })
    if (!entry.owner?.trim()) incomplete.push({ kind: 'missing-owner', path })
    if (!entry.reason?.trim()) incomplete.push({ kind: 'missing-reason', path })

    const generated = looksGenerated(repo, path, exemptions)
    if (entry.category === 'generated' && !generated) {
      violations.push({ kind: 'category-mismatch', path, detail: 'registered as generated but carries no generated marker' })
    }
    if (entry.category === 'fork' && generated) {
      violations.push({ kind: 'category-mismatch', path, detail: 'carries a generated marker but is registered as a hand-written fork' })
    }
  }
  for (const entry of incomplete) violations.push(entry)

  const forkPaths = [...modified].filter(path => registered.get(path)?.category === 'fork')
  const maxForkFiles = Number(manifest.budget.maxForkFiles)
  if (forkPaths.length > maxForkFiles) {
    violations.push({ kind: 'fork-budget-exceeded', path: `${forkPaths.length} fork files > budget ${maxForkFiles}` })
  }
  if (!options.allowStale) for (const entry of stale) violations.push({ kind: 'stale-registration', path: entry.path })

  if (options.against) {
    const ledger = 'scripts/upgrade/upstream-overrides.json'
    if (!fileExistsAt(repo, options.against, ledger)) {
      process.stderr.write(`upstream overrides: ${options.against} carries no ledger; skipping the new-fork check\n`)
    } else {
      const previousRaw = git(repo, ['show', `${options.against}:${ledger}`])
      let previous
      try {
        previous = JSON.parse(previousRaw)
      } catch {
        throw new Error(`${options.against} carries an unreadable ledger`)
      }
      const previousFork = new Set(previous.entries.filter(entry => entry.category === 'fork').map(entry => entry.path))
      for (const path of forkPaths) {
        if (!previousFork.has(path)) violations.push({ kind: 'new-fork-requires-review', path })
      }
    }
  }

  const report = {
    base: options.base,
    mergeBase,
    modified: modified.size,
    added: added.size,
    registered: registered.size,
    forkFiles: forkPaths.length,
    budget: maxForkFiles,
    violations,
    stale,
    incomplete,
  }

  if (options.json) {
    process.stdout.write(`${JSON.stringify(report, null, 2)}\n`)
  } else if (options.report) {
    process.stdout.write(`fork ${forkPaths.length}/${maxForkFiles}  modified ${modified.size}  registered ${registered.size}\n`)
    for (const entry of incomplete) process.stdout.write(`  TODO ${entry.kind === 'missing-owner' ? 'owner' : 'reason'}: ${entry.path}\n`)
  } else {
    process.stdout.write(`upstream base: ${options.base} (${mergeBase.slice(0, 10)})\n`)
    process.stdout.write(`fork ${forkPaths.length}/${maxForkFiles}  modified ${modified.size}  added ${added.size}  registered ${registered.size}\n`)
    for (const violation of violations) {
      process.stdout.write(`  FAIL ${violation.kind}: ${violation.path}${violation.detail ? ` (${violation.detail})` : ''}\n`)
    }
    if (violations.length === 0) process.stdout.write('overrides: in budget\n')
  }

  return violations.length === 0 ? 0 : 1
}

try {
  process.exitCode = main()
} catch (error) {
  process.stderr.write(`verify-upstream-overrides: ${error instanceof Error ? error.message : String(error)}\n`)
  process.exitCode = 2
}
